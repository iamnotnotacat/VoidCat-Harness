export function osintDirectoryHost(entry: OsintDirectoryEntry) {
  try { return new URL(entry.url).hostname.replace(/^www\./, ""); } catch { return "external resource"; }
}

export function describeOsintDirectoryEntry(entry: OsintDirectoryEntry) {
  if (entry.sourceDescription) return entry.sourceDescription;
  const category = OSINT4ALL_CATEGORY_DESCRIPTIONS[entry.category] ?? "Externally curated OSINT resource.";
  return `${category} OSINT4All lists this entry as “${entry.name}”; hosted at ${osintDirectoryHost(entry)}.`;
}

const DIRECTORY_QUERY_ALIASES: Readonly<Record<string, readonly string[]>> = {
  geolocation: ["geo", "geospatial", "maps", "mapping"],
  location: ["geo", "geospatial", "maps", "mapping"],
  aircraft: ["flight", "aviation", "maps"],
  vessel: ["ship", "maritime", "maps"],
  person: ["people", "public-record"],
};

export function searchOsintDirectory(query: string, limit = 50) {
  const words = query.toLowerCase().match(/[a-z0-9.-]{2,}/g)?.filter((word) => !["the", "and", "for", "with", "tool", "tools", "search", "find"].includes(word)) ?? [];
  const terms = [...new Set(words.flatMap((word) => [word, ...(DIRECTORY_QUERY_ALIASES[word] ?? [])]))];
  if (!terms.length) return OSINT4ALL_LINKS.slice(0, Math.max(1, Math.min(limit, 100)));
  return OSINT4ALL_LINKS.map((entry) => {
    const haystack = `${entry.name} ${entry.category} ${entry.url} ${describeOsintDirectoryEntry(entry)}`.toLowerCase();
    const score = terms.reduce((total, term) => total + (haystack.includes(term) ? (entry.name.toLowerCase().includes(term) || entry.category.toLowerCase().includes(term) ? 3 : 1) : 0), 0);
    return { entry, score };
  }).filter(({ score }) => score > 0).sort((left, right) => right.score - left.score || left.entry.id.localeCompare(right.entry.id)).slice(0, Math.max(1, Math.min(limit, 100))).map(({ entry }) => entry);
}
